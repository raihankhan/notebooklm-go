// TestBuildListSources_Shape — five-slot shape with the trailing
// `[None, 0]` and the nested template block at slot 2.
func TestBuildListSources_Shape(t *testing.T) {
	got := BuildListSources("nb-1")
	if len(got) != 5 {
		t.Fatalf("BuildListSources len = %d, want 5", len(got))
	}
	if got[1] != nil {
		t.Errorf("BuildListSources slot 1 = %v, want nil", got[1])
	}
	if got[3] != nil {
		t.Errorf("BuildListSources slot 3 = %v, want nil", got[3])
	}
	// slot 4 is the trailing zero.
	if got[4] != 0 {
		t.Errorf("BuildListSources slot 4 = %v, want 0", got[4])
	}
	// slot 2 is the nested template block.
	if _, ok := got[2].([]any); !ok {
		t.Errorf("BuildListSources slot 2 type = %T, want []any", got[2])
	}
}

// TestBuildAddSourceURL_Shape — three-slot outer shape:
// [spec, notebook_id, template_block].
func TestBuildAddSourceURL_Shape(t *testing.T) {
	got := BuildAddSourceURL("nb-1", "https://example.com")
	if len(got) != 3 {
		t.Fatalf("BuildAddSourceURL len = %d, want 3", len(got))
	}
	if got[1] != "nb-1" {
		t.Errorf("BuildAddSourceURL slot 1 = %v, want \"nb-1\"", got[1])
	}
	// slot 0 is [[spec]] — double-wrapped.
	outer, ok := got[0].([]any)
	if !ok || len(outer) != 1 {
		t.Fatalf("BuildAddSourceURL slot 0 = %v, want [[spec]]", got[0])
	}
	spec, ok := outer[0].([]any)
	if !ok || len(spec) != 12 {
		t.Fatalf("BuildAddSourceURL spec len = %d, want 12", len(spec))
	}
	// spec slot 2 carries the [url] envelope.
	urlEnv, ok := spec[2].([]any)
	if !ok || len(urlEnv) != 1 || urlEnv[0] != "https://example.com" {
		t.Errorf("BuildAddSourceURL spec slot 2 = %v, want [\"https://example.com\"]", spec[2])
	}
	// spec slot 11 carries the trailing literal 1 (source-type code).
	if spec[11] != 1 {
		t.Errorf("BuildAddSourceURL spec slot 11 = %v, want 1", spec[11])
	}
}

// TestBuildAddSourceURL_TemplateBlockFresh — wire.TemplateBlock must
// return a fresh slice every call; the protocol parser rejects shared
// mutable nested literals. We mutate one returned slice and assert the
// next call is unaffected.
func TestBuildAddSourceURL_TemplateBlockFresh(t *testing.T) {
	a := BuildAddSourceURL("alpha", "https://a.example")
	a[2].([]any)[3].([]any)[0] = "MUTATED"
	b := BuildAddSourceURL("beta", "https://b.example")
	if b[2].([]any)[3].([]any)[0] != 1 {
		t.Fatalf("BuildAddSourceURL shared template block; got %v", b[2])
	}
}

// TestBuildAddSourceURL_URLAtSlot2 — the URL rides at source-spec
