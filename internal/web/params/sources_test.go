// TestValidateURL_Accepts — the helper accepts a clean http / https
// URL and rejects every other shape (empty / whitespace / ftp /
// scheme-less).
func TestValidateURL_Accepts(t *testing.T) {
	cases := []string{
		"http://example.com",
		"https://example.com",
		"https://example.com/path?q=1&r=2#fragment",
		"https://example.com:8080/path",
	}
	for _, c := range cases {
		if err := ValidateURL(c); err != nil {
			t.Errorf("ValidateURL(%q) = %v, want nil", c, err)
		}
	}
}

// TestValidateURL_Rejects — the helper rejects empty / whitespace /
// non-http inputs.
func TestValidateURL_Rejects(t *testing.T) {
	cases := []string{
		"",
		"   ",
		"example.com",
		"ftp://example.com",
		"javascript:alert(1)",
		"//example.com",
		"https://example.com\n",
		"\thttps://example.com",
	}
	for _, c := range cases {
		if err := ValidateURL(c); err == nil {
			t.Errorf("ValidateURL(%q) returned nil err; want validation error", c)
		}
	}
}

// TestEncodeNoHTMLEscape — the byte output must not HTML-escape the
// `<`, `>`, or `&` characters (per AGENTS.md rule 3). Pin a builder
// that uses an URL containing these characters to assert the UTF-8
// round-trip.
func TestEncodeNoHTMLEscape_Sources(t *testing.T) {
	got, err := Encode(func() []any {
		return BuildAddSourceURL("nb-1", "https://example.com/?q=<&>")
	})
	if err != nil {
		t.Fatalf("Encode: %v", err)
	}
	for _, esc := range []string{`\u003c`, `\u003e`, `\u0026`} {
		if strings.Contains(string(got), esc) {
			t.Errorf("Encode output contains HTML-escape sequence %s: %s", esc, got)
		}
	}
}

