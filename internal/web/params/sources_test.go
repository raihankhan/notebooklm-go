// Tests for the sources params builders.
//
// The Python original (_web/params/sources.py + _web/sources/add.py)
// is the normative wire-shape source — every builder's output here
// must match what `wire.Marshal` would emit for the equivalent
// positional literal in Python. We assert the byte output below as
// golden strings; a reviewer hand-editing a builder must hand-edit
// the matching golden here in the same commit so the diff is
// traceable.
//
// We do NOT use the testdata/golden.json table that
// `notebooks_test.go` uses — T-P6-1 is the first sources ticket, so
// the testdata file does not yet carry sources builders. The
// expected bytes below were generated by hand-rolling
// `wire.Marshal(BuildListSources(...))` and
// `wire.Marshal(BuildAddSourceURL(...))` in a scratch binary and
// pasting the literal bytes here.
package params

import (
	"strings"
	"testing"
)

// TestBuildListSources_Bytes — the GET_NOTEBOOK shape used by the
// listing surface. The trailing `[None, 0]` and the nested template
// block at slot 2 are load-bearing; pinned verbatim.
func TestBuildListSources_Bytes(t *testing.T) {
	got, err := Encode(func() []any { return BuildListSources("nb-1") })
	if err != nil {
		t.Fatalf("Encode: %v", err)
	}
	// Wire shape: ["nb-1", null, [2, null, null, [1, null×9, [1]]], null, 0]
	// Serialized: ["nb-1",null,[2,null,null,[1,null,null,null,null,null,null,null,null,null,[1]]],null,0]
	want := `["nb-1",null,[2,null,null,[1,null,null,null,null,null,null,null,null,null,[1]]],null,0]`
	if string(got) != want {
		t.Fatalf("BuildListSources bytes differ\n got: %s\nwant: %s", got, want)
	}
}

// TestBuildAddSourceURL_Bytes — the golden encode test pinned
// against Python's `add_url_source` literal. The shape is the
// nested wrapper (#1546 wire migration): a fresh template block at
// slot 2, with the URL riding at source-spec slot 2.
func TestBuildAddSourceURL_Bytes(t *testing.T) {
	got, err := Encode(func() []any { return BuildAddSourceURL("nb-1", "https://example.com") })
	if err != nil {
		t.Fatalf("Encode: %v", err)
	}
	// Wire shape:
	// [
	//   [[null, null, ["https://example.com"], null, null, null, null, null, null, null, 1]],
	//   "nb-1",
	//   [2, null, null, [1, null×9, [1]]]
	// ]
	want := `[[[null,null,["https://example.com"],null,null,null,null,null,null,null,null,1]],"nb-1",[2,null,null,[1,null,null,null,null,null,null,null,null,null,[1]]]]`
	if string(got) != want {
		t.Fatalf("BuildAddSourceURL bytes differ\n got: %s\nwant: %s", got, want)
	}
}

